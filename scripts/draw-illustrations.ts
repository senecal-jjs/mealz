/**
 * Draws the bundled recipes' illustrations into src/catalog/data/illustrations
 * and rewrites its index. Run with `npm run catalog:illustrations` after
 * changing scripts/illustrations or adding a recipe.
 *
 * With `--sheet <file>` it also writes a contact sheet of every drawing (theme
 * colours filled in with their light defaults) for reviewing them together.
 */
import fs from 'node:fs';
import path from 'node:path';

import { dishes, NO_FORK } from './illustrations/dishes';
import { HEIGHT, makeKit, rng, seedFor, WIDTH } from './illustrations/kit';

const dataDir = path.join(__dirname, '../src/catalog/data');
const outDir = path.join(dataDir, 'illustrations');

const ids = fs
  .readdirSync(path.join(dataDir, 'recipes'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort();

const missing = ids.filter((id) => !dishes[id]);
const extra = Object.keys(dishes).filter((id) => !ids.includes(id));
if (missing.length || extra.length) {
  if (missing.length) console.error(`No illustration for: ${missing.join(', ')}`);
  if (extra.length) console.error(`Illustrations for unknown recipes: ${extra.join(', ')}`);
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });
for (const file of fs.readdirSync(outDir)) {
  if (file.endsWith('.svg')) fs.rmSync(path.join(outDir, file));
}

const drawings = new Map<string, string>();
for (const id of ids) {
  const k = makeKit(rng(seedFor(id)));
  const body = k.setting({ fork: !NO_FORK.has(id) }) + dishes[id](k);
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" width="${WIDTH}" height="${HEIGHT}">` +
    `<rect width="${WIDTH}" height="${HEIGHT}" fill="var(--bg, #F6E7D8)"/>${body}</svg>\n`;
  drawings.set(id, svg);
  fs.writeFileSync(path.join(outDir, `${id}.svg`), svg);
}

// Quoted only where needed, as Prettier writes them.
const key = (id: string) => (/^[a-z]+$/.test(id) ? id : `'${id}'`);
const entries = ids.map((id) => `  ${key(id)}: require('./${id}.svg'),`).join('\n');
fs.writeFileSync(
  path.join(outDir, 'index.ts'),
  `// Drawn illustrations for bundled recipes, by recipe id. A recipe's photo
// (\`image\`) wins when it has one. Colours that follow the theme are CSS
// variables in the SVGs, filled in by \`RecipeImage\`.
// Generated by scripts/draw-illustrations.ts: don't edit by hand.
export const illustrations: Record<string, number> = {
${entries}
};
`,
);

const sizes = [...drawings.values()].map((s) => s.length);
console.log(
  `Drew ${ids.length} illustrations, ${Math.round(Math.min(...sizes) / 1024)}–${Math.round(Math.max(...sizes) / 1024)} KB each.`,
);

const sheetAt = process.argv.indexOf('--sheet');
if (sheetAt > 0) {
  const columns = 6;
  const rows = Math.ceil(ids.length / columns);
  const label = 22;
  let sheet = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${columns * WIDTH} ${rows * (HEIGHT + label)}">`;
  ids.forEach((id, i) => {
    const x = (i % columns) * WIDTH;
    const y = Math.floor(i / columns) * (HEIGHT + label);
    const inner = drawings
      .get(id)!
      .replace(/var\(--[a-z-]+, (#[0-9A-Fa-f]+)\)/g, '$1')
      .replace('<svg ', `<svg x="${x}" y="${y}" `);
    sheet +=
      inner +
      `<text x="${x + 8}" y="${y + HEIGHT + 16}" font-family="Helvetica" font-size="15">${id}</text>`;
  });
  fs.writeFileSync(process.argv[sheetAt + 1], sheet + '</svg>\n');
}
